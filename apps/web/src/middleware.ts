import { NextResponse, type NextRequest } from 'next/server';
import { getBackendOrigin } from '../config/api.mjs';

// Identity still comes exclusively from verified NestJS credentials. Do not
// forward caller-supplied tenant/role, forwarding, ingress or Next.js headers.
const forwardedHeaders = [
  'accept', 'accept-language', 'authorization', 'cookie', 'content-type', 'content-encoding', 'content-length',
  'origin', 'sec-fetch-site', 'sec-fetch-mode', 'sec-fetch-dest', 'user-agent',
  'x-auth-mode', 'x-csrf-token', 'idempotency-key', 'x-request-id', 'x-correlation-id',
];

const privateResponseHeaders = {
  'Cache-Control': 'private, no-store',
  'CDN-Cache-Control': 'no-store',
  'Vercel-CDN-Cache-Control': 'no-store',
  'x-vercel-enable-rewrite-caching': '0',
};

function problem(status: number, code: string): NextResponse {
  return NextResponse.json({
    type: 'about:blank', title: code, status, detail: code, code,
  }, { status, headers: { ...privateResponseHeaders, 'Content-Type': 'application/problem+json' } });
}

export function middleware(request: NextRequest): NextResponse {
  if (!process.env.API_BACKEND_ORIGIN) {
    // Preserve legacy direct API development; fail closed in same-origin mode.
    return process.env.NEXT_PUBLIC_API_URL === '/api/v1'
      ? problem(503, 'API_PROXY_UNAVAILABLE') : NextResponse.next();
  }

  // Reject ambiguous encodings before re-encoding or forwarding any path. All
  // API route segments are ASCII slugs/UUIDs. Queries retain their encoding.
  const path = request.nextUrl.pathname;
  if (!/^\/api\/v1(?:\/[A-Za-z0-9_-]+)*\/?$/.test(path)) {
    return problem(404, 'NOT_FOUND');
  }
  if (/^\/api\/v1\/internal(?:\/|$)/i.test(path)) return problem(404, 'NOT_FOUND');

  let origin: string;
  try {
    origin = getBackendOrigin(process.env.API_BACKEND_ORIGIN, process.env.NODE_ENV === 'production');
  } catch {
    return problem(503, 'API_PROXY_UNAVAILABLE');
  }
  if (origin === request.nextUrl.origin) return problem(503, 'API_PROXY_UNAVAILABLE');
  const destination = new URL(path + request.nextUrl.search, origin);
  // Next 15 treats an empty override list as absent. Keep one safe header so
  // requests containing only disallowed headers are still stripped.
  const headers = new Headers({ accept: request.headers.get('accept') ?? 'application/json' });
  for (const name of forwardedHeaders) {
    const value = request.headers.get(name);
    if (value !== null) headers.set(name, value);
  }
  // Host/forwarding are generated by the transport, never copied from callers.
  // Do not read/clone the body: the external rewrite retains its exact bytes.
  return NextResponse.rewrite(destination, {
    request: { headers }, headers: privateResponseHeaders,
  });
}

export const config = { matcher: ['/api/v1/:path*'] };
