-- PROPUESTA: sólo proyectos nuevos dedicados; requiere ACK antes de ejecutar.
-- Identidades NOLOGIN sin contraseñas. Habilitar LOGIN/SCRAM externamente por operador.
BEGIN;
CREATE ROLE bi_migrator NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE bi_api_reader NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE bi_control NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE bi_etl_writer NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO bi_migrator;
DO $$ BEGIN EXECUTE format('GRANT CONNECT, CREATE ON DATABASE %I TO bi_migrator', current_database()); END $$;
DO $$ BEGIN EXECUTE format('GRANT CONNECT ON DATABASE %I TO bi_api_reader', current_database()); END $$;
DO $$ BEGIN EXECUTE format('GRANT CONNECT ON DATABASE %I TO bi_control', current_database()); END $$;
DO $$ BEGIN EXECUTE format('GRANT CONNECT ON DATABASE %I TO bi_etl_writer', current_database()); END $$;
ALTER DEFAULT PRIVILEGES FOR ROLE bi_migrator REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES FOR ROLE bi_migrator REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES FOR ROLE bi_migrator REVOKE ALL ON FUNCTIONS FROM PUBLIC, anon, authenticated, service_role;
COMMIT;
