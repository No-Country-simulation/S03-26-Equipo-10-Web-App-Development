-- PROPUESTA: sólo proyectos nuevos dedicados; requiere ACK antes de ejecutar.
-- Identidades NOLOGIN sin contraseñas. Habilitar LOGIN/SCRAM externamente por operador.
BEGIN;
CREATE ROLE cms_migrator NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE cms_runtime NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE bi_source_reader NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO cms_migrator;
DO $$ BEGIN EXECUTE format('GRANT CONNECT, CREATE ON DATABASE %I TO cms_migrator', current_database()); END $$;
DO $$ BEGIN EXECUTE format('GRANT CONNECT ON DATABASE %I TO cms_runtime', current_database()); END $$;
DO $$ BEGIN EXECUTE format('GRANT CONNECT ON DATABASE %I TO bi_source_reader', current_database()); END $$;
ALTER DEFAULT PRIVILEGES FOR ROLE cms_migrator REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES FOR ROLE cms_migrator REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES FOR ROLE cms_migrator REVOKE ALL ON FUNCTIONS FROM PUBLIC, anon, authenticated, service_role;
COMMIT;
